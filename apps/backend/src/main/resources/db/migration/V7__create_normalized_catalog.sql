CREATE TABLE product_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    code VARCHAR(80) NOT NULL,
    display_type VARCHAR(30) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    required BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_product_options_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
    CONSTRAINT uq_product_options_code UNIQUE (product_id, code)
);
CREATE INDEX idx_product_options_product_sort ON product_options(product_id, sort_order);

CREATE TABLE product_option_values (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_id BIGINT NOT NULL,
    label VARCHAR(100) NOT NULL,
    code VARCHAR(80) NOT NULL,
    swatch_hex VARCHAR(9),
    swatch_image_url VARCHAR(2048),
    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_option_values_option FOREIGN KEY (option_id) REFERENCES product_options(id) ON DELETE CASCADE,
    CONSTRAINT uq_option_values_code UNIQUE (option_id, code)
);
CREATE INDEX idx_option_values_option_sort ON product_option_values(option_id, sort_order);

CREATE TABLE product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(180) NOT NULL,
    product_id BIGINT NOT NULL,
    sku VARCHAR(120),
    combination_key VARCHAR(1000) NOT NULL,
    regular_price_cents BIGINT NOT NULL,
    sale_price_cents BIGINT,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    availability_status VARCHAR(30) NOT NULL DEFAULT 'IN_STOCK',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    allow_backorder BOOLEAN NOT NULL DEFAULT FALSE,
    delivery_estimate VARCHAR(160),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_variants_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT uq_variants_public_id UNIQUE (public_id),
    CONSTRAINT uq_variants_combination UNIQUE (product_id, combination_key),
    CONSTRAINT ck_variants_price CHECK (regular_price_cents >= 0),
    CONSTRAINT ck_variants_sale_price CHECK (sale_price_cents IS NULL OR sale_price_cents >= 0),
    CONSTRAINT ck_variants_stock CHECK (stock_quantity >= 0)
);
CREATE INDEX idx_variants_product_active ON product_variants(product_id, active);
CREATE INDEX idx_variants_sku ON product_variants(sku);

CREATE TABLE product_variant_option_values (
    variant_id BIGINT NOT NULL,
    option_value_id BIGINT NOT NULL,
    PRIMARY KEY (variant_id, option_value_id),
    CONSTRAINT fk_variant_values_variant FOREIGN KEY (variant_id) REFERENCES product_variants(id) ON DELETE CASCADE,
    CONSTRAINT fk_variant_values_value FOREIGN KEY (option_value_id) REFERENCES product_option_values(id)
);
CREATE INDEX idx_variant_values_value ON product_variant_option_values(option_value_id);

