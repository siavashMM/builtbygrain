CREATE TABLE storefront_settings (
    id SMALLINT PRIMARY KEY,
    hero_image_url VARCHAR(2048),
    hero_image_alt_text VARCHAR(300),
    hero_heading VARCHAR(300),
    hero_supporting_text VARCHAR(1000),
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT ck_storefront_settings_singleton CHECK (id = 1),
    CONSTRAINT ck_storefront_hero_alt CHECK (hero_image_url IS NULL OR (hero_image_alt_text IS NOT NULL AND LENGTH(TRIM(hero_image_alt_text)) > 0))
);

